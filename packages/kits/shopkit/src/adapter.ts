import type { ModelMap, ModelName } from './types';

export type WhereOperator = 'eq' | 'ne' | 'lt' | 'lte' | 'gt' | 'gte' | 'in';

/**
 * One condition; all conditions of a `where` are AND-ed. `eq`/`ne` with
 * `null` mean IS NULL / IS NOT NULL.
 */
export type Where<M extends ModelName> = {
  [F in keyof ModelMap[M]]: {
    field: F;
    operator?: WhereOperator;
    value: ModelMap[M][F] | ModelMap[M][F][] | null;
  };
}[keyof ModelMap[M]];

export type FindManyOptions<M extends ModelName> = {
  where?: Where<M>[];
  limit?: number;
  /** Rows to skip (paging, together with `sortBy`). */
  offset?: number;
  sortBy?: { field: keyof ModelMap[M]; direction: 'asc' | 'desc' };
};

/**
 * Everything the engine needs from a database. Implement these five methods
 * for any store (SQL, document DB, KV…); `drizzleAdapter` and
 * `memoryAdapter` ship with the package. Same contract as subkit's adapter.
 *
 * Contract:
 * - ids are generated by the engine, the adapter stores them as given;
 * - `update` applies the patch to every row matching `where` and returns the
 *   first updated row, or `null` if nothing matched. The engine relies on this
 *   for compare-and-set (e.g. "set stock to 4 where stock = 5"), so the
 *   update must be atomic per row;
 * - `create` must reject a duplicate `product.slug`, `variant.sku`,
 *   `cart.token`, `discount.code`, `giftCard.code`, `order.number` or
 *   `order.accessToken` (unique constraint);
 * - `transaction` is optional but recommended: without it a crash between two
 *   writes can leave reserved stock without its order.
 */
export interface StorageAdapter {
  id: string;

  create<M extends ModelName>(
    model: M,
    data: ModelMap[M],
  ): Promise<ModelMap[M]>;

  findOne<M extends ModelName>(
    model: M,
    where: Where<M>[],
  ): Promise<ModelMap[M] | null>;

  findMany<M extends ModelName>(
    model: M,
    options?: FindManyOptions<M>,
  ): Promise<ModelMap[M][]>;

  update<M extends ModelName>(
    model: M,
    where: Where<M>[],
    patch: Partial<ModelMap[M]>,
  ): Promise<ModelMap[M] | null>;

  transaction?<R>(fn: (adapter: StorageAdapter) => Promise<R>): Promise<R>;
}

/** Helper for adapters: checks one row against a condition. */
export function matchesWhere(
  row: Record<string, unknown>,
  where: { field: PropertyKey; operator?: WhereOperator; value: unknown }[],
): boolean {
  return where.every((condition) => {
    const actual = normalize(row[condition.field as string]);
    const expected = condition.value;
    const op = condition.operator ?? 'eq';

    if (op === 'in') {
      return (
        Array.isArray(expected) &&
        expected.map(normalize).some((value) => value === actual)
      );
    }

    const value = normalize(expected);

    if (value === null) {
      if (op === 'eq') return actual === null;
      if (op === 'ne') return actual !== null;
      return false;
    }

    if (actual === null) {
      return op === 'ne';
    }

    switch (op) {
      case 'eq':
        return actual === value;
      case 'ne':
        return actual !== value;
      case 'lt':
        return (actual as number) < (value as number);
      case 'lte':
        return (actual as number) <= (value as number);
      case 'gt':
        return (actual as number) > (value as number);
      case 'gte':
        return (actual as number) >= (value as number);
    }
  });
}

function normalize(value: unknown) {
  if (value instanceof Date) return value.getTime();
  if (value === undefined) return null;
  return value;
}
